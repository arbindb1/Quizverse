CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(30) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  xp INT UNSIGNED NOT NULL DEFAULT 0,
  wins INT UNSIGNED NOT NULL DEFAULT 0,
  tournaments INT UNSIGNED NOT NULL DEFAULT 0,
  skin VARCHAR(30) NOT NULL DEFAULT 'rookie',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(50) NOT NULL UNIQUE,
  created_by INT UNSIGNED NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS quizzes (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  owner_id INT UNSIGNED NOT NULL,
  category_id INT UNSIGNED NULL,
  title VARCHAR(120) NOT NULL,
  description VARCHAR(500) NOT NULL DEFAULT '',
  is_public TINYINT(1) NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (owner_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS questions (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  quiz_id INT UNSIGNED NOT NULL,
  position INT NOT NULL DEFAULT 0,
  text VARCHAR(500) NOT NULL,
  options JSON NOT NULL,
  correct_index TINYINT UNSIGNED NOT NULL,
  time_limit SMALLINT UNSIGNED NOT NULL DEFAULT 20,
  FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS rooms (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  code CHAR(6) NOT NULL UNIQUE,
  invite_token CHAR(24) NOT NULL UNIQUE,
  host_id INT UNSIGNED NOT NULL,
  quiz_id INT UNSIGNED NULL,
  game_type ENUM('quiz','typerace') NOT NULL DEFAULT 'quiz',
  text_length ENUM('short','medium','long') NOT NULL DEFAULT 'medium',
  name VARCHAR(80) NOT NULL,
  max_players TINYINT UNSIGNED NOT NULL DEFAULT 8,
  bot_enabled TINYINT(1) NOT NULL DEFAULT 0,
  bot_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
  bot_difficulty ENUM('easy','medium','hard') NOT NULL DEFAULT 'medium',
  questions_per_match TINYINT UNSIGNED NOT NULL DEFAULT 3,
  status ENUM('lobby','playing','finished') NOT NULL DEFAULT 'lobby',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  started_at TIMESTAMP NULL,
  finished_at TIMESTAMP NULL,
  FOREIGN KEY (host_id) REFERENCES users(id) ON DELETE CASCADE,
  FOREIGN KEY (quiz_id) REFERENCES quizzes(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS room_players (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  room_id INT UNSIGNED NOT NULL,
  user_id INT UNSIGNED NULL,
  is_bot TINYINT(1) NOT NULL DEFAULT 0,
  display_name VARCHAR(30) NOT NULL,
  skin VARCHAR(30) NULL,
  score INT NOT NULL DEFAULT 0,
  placement SMALLINT UNSIGNED NULL,
  joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_room_user (room_id, user_id),
  FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS room_answers (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  room_id INT UNSIGNED NOT NULL,
  player_id INT UNSIGNED NOT NULL,
  question_id INT UNSIGNED NOT NULL,
  choice TINYINT NULL,
  is_correct TINYINT(1) NOT NULL DEFAULT 0,
  points INT NOT NULL DEFAULT 0,
  time_ms INT NULL,
  match_no SMALLINT NOT NULL DEFAULT 0,
  FOREIGN KEY (room_id) REFERENCES rooms(id) ON DELETE CASCADE,
  FOREIGN KEY (player_id) REFERENCES room_players(id) ON DELETE CASCADE
) ENGINE=InnoDB;
